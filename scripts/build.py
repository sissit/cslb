def url(lang, page):
    return SITE + PREFIX[lang] + ('' if page == 'index' else page + '.html')


def strip_langs(s, keep):
    """Remove every element whose class includes l-xx for a language other than keep."""
    pat = re.compile(r'<(\w+)\b[^>]*\bclass="[^"]*\bl-(zh|en|es)\b[^"]*"[^>]*>')
    pos = 0
    while True:
        m = pat.search(s, pos)
        if not m:
            return s
        tag, lg = m.group(1), m.group(2)
        if lg == keep:
            pos = m.end()
            continue
        depth, i = 1, m.end()
        tok = re.compile(r'<(/?)%s\b[^>]*>' % tag)
        while depth:
            t = tok.search(s, i)
            depth += -1 if t.group(1) else 1
            i = t.end()
        # drop the element and trailing whitespace on its line
        j = i
        while j < len(s) and s[j] in ' \t':
            j += 1
        if j < len(s) and s[j] == '\n':
            j += 1
        s = s[:m.start()] + s[j:]
        pos = m.start()


def head(lang, page, title, desc, alts):
    """alts: {lang: absolute url} for this page in every language."""
    tags = [f'<title>{html.escape(title)}</title>',
            f'<meta name="description" content="{html.escape(desc)}">',
            f'<link rel="canonical" href="{alts[lang]}">']
    tags += [f'<link rel="alternate" hreflang="{HREFLANG[l]}" href="{alts[l]}">' for l in LANGS]
    tags.append(f'<link rel="alternate" hreflang="x-default" href="{alts["en"]}">')
    tags += ['<meta property="og:type" content="website">',
             '<meta property="og:site_name" content="CSLB Prep">',
             f'<meta property="og:title" content="{html.escape(title)}">',
             f'<meta property="og:description" content="{html.escape(desc)}">',
             f'<meta property="og:url" content="{alts[lang]}">',
             f'<meta property="og:image" content="{SITE}/assets/og-{lang}.png">',
             '<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">',
             f'<meta property="og:locale" content="{OG_LOCALE[lang]}">',
             '<meta name="twitter:card" content="summary_large_image">']
    if page == 'index':
        ld = {'@context': 'https://schema.org', '@type': 'WebSite', 'name': 'CSLB Prep', 'alternateName': 'CSLB 备考',
              'url': alts[lang], 'inLanguage': HTML_LANG[lang], 'description': desc}
        tags.append('<script type="application/ld+json">' + json.dumps(ld, ensure_ascii=False) + '</script>')
    # send visitors who chose another language before to their version (only when arriving from outside the site)
    tags.append("<script>try{var l=JSON.parse(localStorage.getItem('cslb-lang')||'null');"
                f"if(l&&l!=='{lang}'&&['en','zh','es'].indexOf(l)>=0&&!/^https?:\\/\\/(cslbexam\\.org|localhost|127\\.)/.test(document.referrer))"
                "location.replace((l==='en'?'/':'/'+l+'/')+location.pathname.replace(/^\\/(zh|es)\\//,'/').replace(/^\\//,'')+location.search+location.hash)}catch(e){}</script>")
    return '\n'.join(tags)


def clean_head(s):
    s = re.sub(r'<script>try\{var l=JSON\.parse\(localStorage[^<]*</script>\n?', '', s)
    s = re.sub(r'<title>[^<]*</title>\n?', '', s)
    s = re.sub(r'<meta name="(title-\w+|description|twitter:card)"[^>]*>\n?', '', s)
    s = re.sub(r'<meta property="og:[^"]*"[^>]*>\n?', '', s)
    s = re.sub(r'<link rel="(canonical|alternate)"[^>]*>\n?', '', s)
    s = re.sub(r'<script type="application/ld\+json">.*?</script>\n?', '', s, flags=re.S)
    s = re.sub(r'(href|src)="(assets|content)/', r'\1="/\2/', s)
    return s


def put_head(s, lang, block):
    s = re.sub(r'<html lang="[^"]*">', f'<html lang="{HTML_LANG[lang]}">', s, count=1)
    s = s.replace('<meta name="viewport" content="width=device-width,initial-scale=1">',
                  '<meta name="viewport" content="width=device-width,initial-scale=1">\n' + block, 1)
    return s.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + GEN, 1)


def write(path, s):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, 'w').write(s)


def chapters(notes_lang_html, lang):
    """Split one language's notes page into [(slug, heading, section_html)]."""
    m = re.search(r'<div class="l-%s">\n(.*)</div>\s*</main>' % lang, notes_lang_html, re.S)
    body = m.group(1)
    parts = re.split(r'(?=<h2 id=")', body)
    out = []
    for p in parts[1:]:
        h = re.match(r'<h2 id="([a-z]+)(?:-%s)?">(.*?)</h2>' % lang, p, re.S)
        slug, heading = h.group(1), h.group(2)
        out.append((slug, heading, p[h.end():].rstrip()))
    return out


def main():
    sitemap = []
    for page in PAGES:
        src = clean_head(open(os.path.join(ROOT, 'src', page + '.html')).read())
        alts = {l: url(l, page) for l in LANGS}
        for lang in LANGS:
            s = strip_langs(src, lang)
            if page == 'notes':
                # add a link from each chapter heading to its own page
                s = re.sub(r'<h2 id="([a-z]+)((?:-\w+)?)">(.*?)</h2>',
                           lambda m: f'<h2 id="{m.group(1)}{m.group(2)}">{m.group(3)} <a class="h2link" href="notes-{m.group(1)}.html">{CH[lang]["own"]} →</a></h2>', s)
            s = put_head(s, lang, head(lang, page, TITLE[page][lang], DESC[page][lang], alts))
            write(PREFIX[lang].lstrip('/') + page + '.html', s)
        sitemap.append(alts)

    # chapter pages
    notes_src = open(os.path.join(ROOT, 'src', 'notes.html')).read()
    shell = clean_head(notes_src)
    shell = shell[:shell.index('<main')] + '@@MAIN@@' + shell[shell.index('</main>') + len('</main>'):]
    per = {l: chapters(strip_langs(notes_src, l), l) for l in LANGS}
    slugs = [c[0] for c in per['en']]
    for lang in LANGS:
        chs = [c for c in per[lang] if c[0] in slugs]
        t = CH[lang]
        for k, (slug, heading, body) in enumerate(chs):
            plain = re.sub(r'<[^>]+>', '', html.unescape(heading)).strip()
            exam = 'b' if slug == 'b' else 'law'
            topic = re.sub(r'^.*?·\s*', '', plain)
            alts = {l: SITE + PREFIX[l] + f'notes-{slug}.html' for l in LANGS}
            nav = []
            if k > 0:
                nav.append(f'<a class="btn" href="notes-{chs[k-1][0]}.html">← {t["prev"]}</a>')
            nav.append(f'<a class="btn" href="notes.html">{t["back"]}</a>')
            if k < len(chs) - 1:
                nav.append(f'<a class="btn" href="notes-{chs[k+1][0]}.html">{t["next"]} →</a>')
            main_html = (f'<main class="wrap narrow band">\n<div class="l-{lang}">\n'
                         f'  <p class="small"><a href="notes.html">{t["back"]}</a> · {t[exam]}</p>\n'
                         f'  <h1>{heading}</h1>\n{body}\n'
                         f'  <p><a class="btn pri" href="practice.html">{t["cta"]}</a></p>\n'
                         f'  <div class="qnav">{"".join(nav)}</div>\n</div>\n</main>')
            s = shell.replace('@@MAIN@@', main_html)
            title = t['title'].format(h=plain)
            desc = t['desc'].format(h=topic, x=t[exam])
            s = put_head(s, lang, head(lang, 'chapter', title, desc, alts))
            write(PREFIX[lang].lstrip('/') + f'notes-{slug}.html', s)
        if lang == 'en':
            sitemap += [{l: SITE + PREFIX[l] + f'notes-{c[0]}.html' for l in LANGS} for c in chs]

    sm = ['<?xml version="1.0" encoding="UTF-8"?>',
          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for alts in sitemap:
        for lang in LANGS:
            sm.append(f'  <url><loc>{alts[lang]}</loc><lastmod>{TODAY}</lastmod>')
            sm += [f'    <xhtml:link rel="alternate" hreflang="{HREFLANG[l]}" href="{alts[l]}"/>' for l in LANGS]
            sm.append(f'    <xhtml:link rel="alternate" hreflang="x-default" href="{alts["en"]}"/>')
            sm.append('  </url>')
    sm.append('</urlset>\n')
    write('sitemap.xml', '\n'.join(sm))
    write('robots.txt', f'User-agent: *\nDisallow: /admin/\nDisallow: /api/\nDisallow: /src/\n\nSitemap: {SITE}/sitemap.xml\n')
    print('pages:', len(sitemap) * 3)


if __name__ == '__main__':
    main()
